"""
Pricing Agent  (decision_type: price_adjustment)
================================================
recommendation = suggested price delta from current unit_price (positive = raise,
                 negative = lower)

Algorithm:
  - Fetch trailing 180 days of SalesRecord with varying prices (generated by
    the Phase 2 synthetic data generator with known ground-truth elasticity).
  - Log-log OLS regression: log(qty_sold) ~ β₀ + β₁ * log(price)
    β₁ = price elasticity of demand (negative for normal goods).
  - Optimal delta: push price toward the revenue-maximising price given the
    estimated elasticity.  For a constant-elasticity demand curve, revenue is
    maximised when elasticity ≈ -1; the agent recommends moving toward that point.
  - confidence = R² of the regression (clamped [0,1]).
  - risk_score = clamp(|delta| / current_price, 0, 1).
  - priority = clamp((1 - margin_ratio) * |elasticity|, 0, 1) —
    urgent when margin is thin AND demand is highly elastic.
"""

from datetime import date, timedelta
import math
import numpy as np
from sqlalchemy.orm import Session

from backend.app.agents.base import BaseAgent, DecisionObject
from backend.app.db import SalesRecord, Product
from backend.app.retrieval import get_vector_context

# Minimum data points required to run the regression; below this threshold the
# agent falls back to a neutral recommendation with low confidence.
_MIN_REGRESSION_POINTS = 10

# Fraction of the revenue-gap the agent recommends closing in one step.
# Keeps changes conservative (e.g. 25% of the theoretical optimum delta).
_STEP_FRACTION = 0.25


class PricingAgent(BaseAgent):
    def __init__(self):
        super().__init__(agent_id="pricing")

    def run(
        self,
        tenant_id: str,
        product_id: str,
        run_date: date,
        db: Session,
    ) -> DecisionObject:

        # ── 1. Retrieve product and 180-day price + sales history ─────────
        product = db.query(Product).filter_by(
            tenant_id=tenant_id, id=product_id
        ).first()

        current_price = product.unit_price if product else 10.0
        unit_cost = product.unit_cost if product else 5.0
        margin_ratio = (current_price - unit_cost) / max(current_price, 0.01)

        start_180 = run_date - timedelta(days=180)
        records = db.query(SalesRecord).filter(
            SalesRecord.tenant_id == tenant_id,
            SalesRecord.product_id == product_id,
            SalesRecord.date >= start_180,
            SalesRecord.date <= run_date,
            SalesRecord.price > 0,
            SalesRecord.qty_sold > 0,
        ).all()

        # ── 2. Log-log OLS regression ─────────────────────────────────────
        elasticity, r_squared, price_delta = self._estimate_elasticity_and_delta(
            records, current_price, unit_cost
        )

        confidence = float(np.clip(r_squared, 0.0, 1.0))
        risk_score = float(np.clip(abs(price_delta) / max(current_price, 0.01), 0.0, 1.0))
        # Priority: low margin + high |elasticity| = urgent pricing action
        priority = float(np.clip((1.0 - margin_ratio) * min(abs(elasticity), 3.0) / 3.0, 0.0, 1.0))

        expected_cost = 0.0  # pricing decisions don't incur procurement cost
        avg_daily_qty = (
            float(np.mean([r.qty_sold for r in records])) if records else 1.0
        )
        # Expected benefit = estimated revenue change over 30 days
        new_price = current_price + price_delta
        old_revenue_30 = avg_daily_qty * current_price * 30
        # Demand at new price via constant-elasticity approximation
        if elasticity != 0 and current_price > 0:
            qty_ratio = (new_price / current_price) ** elasticity
        else:
            qty_ratio = 1.0
        new_revenue_30 = avg_daily_qty * qty_ratio * new_price * 30
        expected_benefit = new_revenue_30 - old_revenue_30

        # ── 3. Vector context for historical similarity ───────────────────
        category = product.category if product else "General"
        prod_name = product.name if product else "Product"
        vector_hits, _ = get_vector_context(
            tenant_id=tenant_id,
            agent_id=self.agent_id,
            product_name=prod_name,
            category=category,
            decision_type="price_adjustment",
            current_date=run_date,
            limit=1,
        )
        hist_sim = float(vector_hits[0]["score"]) if vector_hits else 0.5
        hist_sim = float(np.clip(hist_sim, 0.0, 1.0))

        reason = (
            f"Pricing Agent estimated demand elasticity = {elasticity:.3f} "
            f"(R²={r_squared:.3f}) from {len(records)} sales observations over 180 days. "
            f"Recommending a price delta of {price_delta:+.2f} (current: {current_price:.2f} → "
            f"proposed: {new_price:.2f}). Margin ratio: {margin_ratio:.1%}. "
            f"Estimated 30-day revenue impact: {expected_benefit:+.2f}."
        )
        if len(records) < _MIN_REGRESSION_POINTS:
            reason = (
                f"Insufficient price variation data ({len(records)} records). "
                f"Neutral recommendation with low confidence."
            )

        return DecisionObject(
            agent_id=self.agent_id,
            recommendation=price_delta,
            reason=reason,
            confidence=confidence,
            priority=priority,
            risk_score=risk_score,
            expected_cost=expected_cost,
            expected_benefit=float(expected_benefit),
            required_resources={},
            historical_similarity=hist_sim,
        )

    # ── Private helpers ───────────────────────────────────────────────────

    def _estimate_elasticity_and_delta(
        self, records: list, current_price: float, unit_cost: float
    ) -> tuple[float, float, float]:
        """
        Returns (elasticity, r_squared, recommended_price_delta).

        Elasticity is the OLS slope coefficient β₁ of:
            log(qty_sold) = β₀ + β₁ * log(price) + ε

        A negative β₁ means demand falls as price rises (normal good).
        Revenue-maximising price for constant-elasticity curve:
            P* = unit_cost * β₁ / (β₁ + 1)   [monopoly profit max]
        The agent recommends _STEP_FRACTION of (P* - current_price).
        """
        if len(records) < _MIN_REGRESSION_POINTS:
            return 0.0, 0.0, 0.0

        log_qty   = np.array([math.log(max(r.qty_sold, 1)) for r in records], dtype=float)
        log_price = np.array([math.log(max(r.price, 0.01)) for r in records], dtype=float)

        # OLS via lstsq
        A = np.column_stack([np.ones_like(log_price), log_price])
        try:
            result = np.linalg.lstsq(A, log_qty, rcond=None)
            beta = result[0]  # [intercept, slope]
        except np.linalg.LinAlgError:
            return 0.0, 0.0, 0.0

        elasticity = float(beta[1])

        # R² computation
        y_hat = A @ beta
        ss_res = float(np.sum((log_qty - y_hat) ** 2))
        ss_tot = float(np.sum((log_qty - log_qty.mean()) ** 2))
        r_squared = max(0.0, 1.0 - ss_res / max(ss_tot, 1e-9))

        # Revenue-maximising price (only meaningful when elasticity < -1)
        if elasticity < -1.0:
            # P* = unit_cost * |elasticity| / (|elasticity| - 1)
            abs_e = abs(elasticity)
            p_star = unit_cost * abs_e / (abs_e - 1.0)
        else:
            # Inelastic demand or positive elasticity — recommend a small price increase
            p_star = current_price * 1.05

        # Conservative step toward optimum
        raw_delta = (p_star - current_price) * _STEP_FRACTION

        # Clip to ±30% of current price per cycle
        max_delta = current_price * 0.30
        price_delta = float(np.clip(raw_delta, -max_delta, max_delta))

        return elasticity, r_squared, price_delta
